// clod:simple-settings — какую часть секции настроек показывать.
//
//   `all`  — расширенный режим: всё, в прежнем порядке;
//   `core` — простой режим: только повседневное (ТЗ F3.3) плюс то, без чего
//            пользователь не сможет назвать свою версию и попросить помощь;
//   `rest` — остальное, внутри раскрывающегося блока «Продвинутые настройки».
//
// Тип живёт в отдельном `.ts`, а не рядом с компонентом: из `.tsx` в этом
// проекте нельзя экспортировать ничего, кроме компонентов.
export type SettingVariant = 'all' | 'core' | 'rest'
