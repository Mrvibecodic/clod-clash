import { load } from 'js-yaml'

import { debugLog } from './debug'

/**
 * Разбор YAML, который НЕ бросает.
 *
 * Три исхода вместо двух, и разница между ними важна:
 * * `null` — документ пуст (или в нём одни комментарии);
 * * `undefined` — документ сломан;
 * * значение — разобралось.
 *
 * Зачем: редакторы профиля держат разобранный список в состоянии и обратно
 * сериализуют его в файл. Если разбор бросил, состояние остаётся пустым, и
 * сериализатор пишет `prepend: []` поверх файла пользователя — правки
 * исчезают молча. Пустой файл и сломанный файл требуют РАЗНОГО поведения:
 * первый можно спокойно наполнять, второй нельзя трогать вовсе, пока человек
 * не починит его руками в текстовом режиме.
 */
export const parseYamlSafe = (input: string) => {
  const blank = input
    .split(/\r?\n/u)
    .every((line) => line.trim() === '' || line.trimStart().startsWith('#'))
  if (blank) return null

  try {
    return load(input) ?? null
  } catch (error) {
    debugLog('[parseYamlSafe] разбор не удался:', error)
    return undefined
  }
}
